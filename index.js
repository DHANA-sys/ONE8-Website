function showCategory(category) {
    cont.innerHTML = ""; // Clear container first
    
    // Filter products matching the category
    var filteredProducts = product.filter(function(item) {
        return item.category === category;
    });

    // If no products found for that specific category, show a message
    if (filteredProducts.length === 0) {
        cont.innerHTML = `<p style="color:white; font-size:18px;">No products found in this category.</p>`;
        return;
    }

    // Loop through and render all matching products
    filteredProducts.forEach(function(item) {
        let cart = document.createElement("div");
        cart.className = "cart";

        cart.innerHTML = `
            <div class="p-image">
                <img src="${item.Image}" alt="${item.model}">
            </div>
            <div class="p-details">
                <h3>${item.style}</h3>
                <h3>${item.model}</h3>
                <h3>₹${item.price.toLocaleString('en-IN')}</h3>
                <button class="add-btn">
                    <i class="fa-solid fa-cart-plus"></i> Add To Bag
                </button>
            </div>
        `;

        let add_btn = cart.querySelector(".add-btn");
        add_btn.addEventListener("click", function() {
            addCart(item);
        });
        
        cont.appendChild(cart);
    });
}


