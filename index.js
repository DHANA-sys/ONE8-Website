// Cart Drawer Logic
function showCart() {
    var cartBox = document.getElementById('cart-box');
    var backdrop = document.getElementById('cart-backdrop');
    var cartItemsBox = document.getElementById('cart-items');
    var summary = document.getElementById("summary");

    cartBox.classList.add("open");
    backdrop.classList.add("show");

    cartItemsBox.innerHTML = "";
    if (cartItem.length === 0) {
        cartItemsBox.innerHTML = "<p style='text-align:center; color:#888;'>Your cart is empty.</p>";
        summary.innerHTML = "";
        return;
    }

    cartItem.forEach((item, index) => {
        cartItemsBox.innerHTML += `
            <div class="cart-product">
                <img src="${item.Image}" alt="${item.model}" class="i-image">
                <div>
                    <h4 style="font-size:0.9rem;">${item.model}</h4>
                    <p style="font-size:0.85rem; color:#e63946;">₹${(item.price * item.quantity).toLocaleString('en-IN')}</p>
                </div>
                <div>
                    <button onclick="decrease(${index})">-</button>
                    <span style="margin: 0 5px;">${item.quantity}</span>
                    <button onclick="increase(${index})">+</button>
                </div>
            </div>
        `;
    });

    summary.innerHTML = `
        <button class="summary-btn" onclick="goToCheckout()">PROCEED TO CHECKOUT</button>
    `;
}

function closeCart() {
    document.getElementById("cart-box").classList.remove("open");
    document.getElementById("cart-backdrop").classList.remove("show");
}

function addCart(selectedProduct) {
    var exist = cartItem.find(item => item.id === selectedProduct.id);
    if (exist) {
        exist.quantity++;
    } else {
        cartItem.push({ ...selectedProduct, quantity: 1 });
    }
    updateCount();
    showCart();
}

function increase(index) {
    cartItem[index].quantity++;
    showCart();
    updateCount();
}

function decrease(index) {
    if (cartItem[index].quantity > 1) {
        cartItem[index].quantity--;
    } else {
        cartItem.splice(index, 1);
    }
    showCart();
    updateCount();
}

function updateCount() {
    var totalCount = cartItem.reduce((sum, item) => sum + item.quantity, 0);
    document.getElementById("count").innerText = totalCount;
}

// Next Page Checkout Flow Logic
function goToCheckout() {
    if (cartItem.length === 0) return;
    closeCart();
    hideAllSections();
    
    document.getElementById('checkout-page').classList.remove('hidden');

    var summaryItems = document.getElementById("checkoutSummaryItems");
    var totalAmountBox = document.getElementById("checkoutTotalAmount");

    summaryItems.innerHTML = "";
    var total = 0;

    cartItem.forEach(item => {
        var itemTotal = item.price * item.quantity;
        total += itemTotal;
        summaryItems.innerHTML += `
            <div style="display:flex; justify-content:space-between; margin-bottom:8px; font-size:0.9rem;">
                <span>${item.model} (x${item.quantity})</span>
                <span>₹${itemTotal.toLocaleString('en-IN')}</span>
            </div>
        `;
    });

    totalAmountBox.innerText = `₹${total.toLocaleString('en-IN')}`;
}

function handleCheckout(e) {
    e.preventDefault();
    document.getElementById("successModal").classList.remove("hidden");
}

function resetApp() {
    cartItem = [];
    updateCount();
    document.getElementById("successModal").classList.add("hidden");
    showHome();
}

